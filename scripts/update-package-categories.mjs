// Builds src/data/package-categories.js from the official package categories on foundryvtt.com.
// Usage: npm run update:categories [-- --force]
// --force skips the shrink check, for intended big changes such as a new parsing rule
import { writeFile } from "node:fs/promises";

const BASE_URL = "https://foundryvtt.com/packages/tag";
const OUTPUT = new URL("../src/data/package-categories.js", import.meta.url);

// Official foundryvtt.com tag -> Tidy UI category
const TAGS = {
  adventures: "adventures",
  audio: "sounds",
  visuals: "visual",
};

// foundryvtt.com/robots.txt asks for a 4 second crawl delay
const CRAWL_DELAY_MS = 4000;
const REQUEST_TIMEOUT_MS = 30000;
// Sanity limit only: a tag with more pages fails loudly instead of being truncated
const MAX_PAGES = 500;
// Refuse to write a category that shrank below this share of the current data
const MIN_KEPT_SHARE = 0.75;
const FORCE = process.argv.includes("--force");

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

async function fetchPage(tag, page) {
  const url = `${BASE_URL}/${tag}${page > 1 ? `?page=${page}` : ""}`;
  const response = await fetch(url, {
    headers: { "User-Agent": "tidy-ui_game-settings category updater" },
    signal: AbortSignal.timeout(REQUEST_TIMEOUT_MS),
  });
  if (!response.ok) throw new Error(`${url} answered ${response.status}`);
  return response.text();
}

// The listing has one section per package type; only "Add-on Modules" is relevant
function moduleIds(html) {
  const section = html
    .split('<h2 class="border">')
    .find((part) => part.startsWith("Add-on Modules"));
  if (!section) return [];

  return [...section.matchAll(/class="package-title">\s*<a href="\/packages\/([^"/?#]+)/g)].map(
    (match) => {
      try {
        return decodeURIComponent(match[1]);
      } catch {
        return match[1];
      }
    }
  );
}

function readPageCount(html, tag) {
  const pager = html.match(/Page 1 of (\d+)/);
  if (pager) return Number(pager[1]);
  // No pager text is only fine when there is no second page to miss
  if (html.includes('href="?page=2"')) {
    throw new Error(`Tag "${tag}" has more pages but the pager text was not recognized`);
  }
  return 1;
}

async function fetchTag(tag) {
  const ids = new Set();
  let pageCount = 1;

  for (let page = 1; page <= pageCount; page++) {
    if (page > 1) await sleep(CRAWL_DELAY_MS);
    const html = await fetchPage(tag, page);

    if (page === 1) {
      pageCount = readPageCount(html, tag);
      if (pageCount > MAX_PAGES) {
        throw new Error(`Tag "${tag}" has ${pageCount} pages, more than MAX_PAGES (${MAX_PAGES})`);
      }
    }
    for (const id of moduleIds(html)) ids.add(id);
    console.log(`${tag}: page ${page}/${pageCount}, ${ids.size} modules`);
  }

  return [...ids].sort();
}

async function loadCurrentData() {
  try {
    return (await import(OUTPUT.href)).OFFICIAL_CATEGORIES;
  } catch {
    return {};
  }
}

const current = await loadCurrentData();
const categories = {};
for (const [tag, category] of Object.entries(TAGS)) {
  if (Object.keys(categories).length) await sleep(CRAWL_DELAY_MS);
  const ids = await fetchTag(tag);

  // An empty or much smaller list means the page layout changed, never overwrite good data with it
  const previous = current[category]?.length ?? 0;
  if (!ids.length || (!FORCE && ids.length < previous * MIN_KEPT_SHARE)) {
    throw new Error(
      `Tag "${tag}" returned ${ids.length} modules (was ${previous}), has the page layout changed?`
    );
  }
  categories[category] = ids;
}

const source = `// Generated by scripts/update-package-categories.mjs from ${BASE_URL}/* - do not edit.
// Module ids listed under the official foundryvtt.com categories, per Tidy UI category.
export const OFFICIAL_CATEGORIES = ${JSON.stringify(categories, null, 2)};
`;
await writeFile(OUTPUT, source);
console.log(`Wrote ${OUTPUT.pathname}`);
